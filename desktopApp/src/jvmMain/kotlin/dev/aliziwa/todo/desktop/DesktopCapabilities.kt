package dev.aliziwa.todo.desktop

import dev.aliziwa.todo.platform.PlatformCapabilities
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.awt.Desktop
import java.io.File
import java.net.URI
import java.util.concurrent.TimeUnit

/**
 * macOS extras: LaunchAgent install/remove (launch at login + KeepAlive so the app is resident and
 * can fire its own alarms), opening Hugging Face links, and raising our window.
 *
 * The LaunchAgent points at:
 *  - `/Applications/PersonalTodo.app/Contents/MacOS/PersonalTodo` when we are running from a
 *    packaged app (jpackage sets `jpackage.app-path`), falling back to the real launcher path we
 *    were started from if the app lives somewhere else; otherwise
 *  - a generated `~/Library/Application Support/PersonalTodo/run-dev.sh` that runs
 *    `./gradlew :desktopApp:run` in this checkout, so launch-at-login is testable before packaging.
 */
class DesktopCapabilities(
    private val paths: DesktopPaths,
    private val ui: DesktopUiController,
) : PlatformCapabilities {

    override val platformName: String = "macOS"

    /** Only macOS installs a LaunchAgent, so only macOS shows the Settings toggle. */
    override val supportsLaunchAtLogin: Boolean = true

    /** jpackage sets `jpackage.app-version` in the packaged .app; empty under `:desktopApp:run`. */
    override val appVersion: String = System.getProperty("jpackage.app-version").orEmpty()

    override suspend fun setLaunchAtLogin(enabled: Boolean): Boolean = withContext(Dispatchers.IO) {
        runCatching { if (enabled) installAgent() else removeAgent() }
            .onFailure { DesktopLog.e(TAG, "setLaunchAtLogin($enabled) failed", it) }
            .getOrDefault(false)
    }

    override suspend fun isLaunchAtLoginEnabled(): Boolean = withContext(Dispatchers.IO) {
        if (!plistFile.exists()) return@withContext false
        // The plist can exist while being booted out; ask launchd for the truth.
        exec(listOf("launchctl", "print", "gui/${uid()}/$LABEL")).exitCode == 0
    }

    override fun bringToFront() {
        ui.bringToFront()
        runCatching {
            val desktop = Desktop.getDesktop()
            if (desktop.isSupported(Desktop.Action.APP_REQUEST_FOREGROUND)) desktop.requestForeground(true)
        }.onFailure { DesktopLog.w(TAG, "requestForeground unsupported", it) }
    }

    override fun openUrl(url: String) {
        runCatching {
            val desktop = Desktop.getDesktop()
            if (desktop.isSupported(Desktop.Action.BROWSE)) {
                desktop.browse(URI(url))
            } else {
                exec(listOf("open", url))
            }
        }.onFailure { DesktopLog.w(TAG, "could not open $url", it) }
    }

    // ---------------------------------------------------------------- LaunchAgent

    val plistFile: File
        get() = File(System.getProperty("user.home"), "Library/LaunchAgents/$LABEL.plist")

    /** True when this process was started from a jpackage/Compose-packaged `.app`. */
    fun isPackaged(): Boolean = System.getProperty("jpackage.app-path") != null ||
        System.getProperty("compose.application.resources.dir") != null

    fun resolveProgramArguments(): List<String> {
        if (isPackaged()) {
            val installed = File(INSTALLED_LAUNCHER)
            if (installed.canExecute()) return listOf(installed.absolutePath, BACKGROUND_FLAG)
            val launcher = System.getProperty("jpackage.app-path")?.let(::File)
            if (launcher != null && launcher.canExecute()) return listOf(launcher.absolutePath, BACKGROUND_FLAG)
            DesktopLog.w(TAG, "packaged but no launcher found; using $INSTALLED_LAUNCHER anyway")
            return listOf(INSTALLED_LAUNCHER, BACKGROUND_FLAG)
        }
        return listOf("/bin/sh", writeDevRunScript().absolutePath)
    }

    /** Generated dev launcher: runs `./gradlew :desktopApp:run` in the checkout we were started from. */
    fun writeDevRunScript(): File {
        val repo = findRepoRoot()
        val script = paths.devRunScript
        script.writeText(
            """
            #!/bin/sh
            # Generated by PersonalTodo (desktop) — dev-mode launch agent target.
            # Replaced automatically; edit the app's Settings instead.
            cd "$repo" || exit 1
            export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
            # main() honours this instead of --background: Gradle's run task owns argv.
            export TODO_START_HIDDEN=1
            exec ./gradlew --console=plain --quiet :desktopApp:run
            """.trimIndent() + "\n",
        )
        script.setExecutable(true)
        return script
    }

    private fun findRepoRoot(): String {
        var dir: File? = File(System.getProperty("user.dir")).absoluteFile
        while (dir != null) {
            if (File(dir, "gradlew").exists() && File(dir, "settings.gradle.kts").exists()) return dir.absolutePath
            dir = dir.parentFile
        }
        return System.getProperty("user.dir")
    }

    private fun buildPlist(): String {
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n")
        sb.append("<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" ")
        sb.append("\"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n")
        sb.append("<plist version=\"1.0\">\n")
        sb.append("<dict>\n")
        sb.append("    <key>Label</key>\n    <string>").append(LABEL).append("</string>\n")
        sb.append("    <key>ProgramArguments</key>\n    <array>\n")
        resolveProgramArguments().forEach { sb.append("        <string>").append(it.escapeXml()).append("</string>\n") }
        sb.append("    </array>\n")
        sb.append("    <key>RunAtLoad</key>\n    <true/>\n")
        sb.append("    <key>KeepAlive</key>\n    <true/>\n")
        sb.append("    <key>ProcessType</key>\n    <string>Interactive</string>\n")
        sb.append("    <key>StandardOutPath</key>\n    <string>")
            .append(File(paths.dataDir, "launchagent.out.log").absolutePath.escapeXml()).append("</string>\n")
        sb.append("    <key>StandardErrorPath</key>\n    <string>")
            .append(File(paths.dataDir, "launchagent.err.log").absolutePath.escapeXml()).append("</string>\n")
        sb.append("</dict>\n</plist>\n")
        return sb.toString()
    }

    private fun installAgent(): Boolean {
        plistFile.parentFile?.mkdirs()
        // Bootout an existing registration first so launchd picks up a changed ProgramArguments.
        if (plistFile.exists()) exec(listOf("launchctl", "bootout", "gui/${uid()}/$LABEL"))
        plistFile.writeText(buildPlist())
        val bootstrap = exec(listOf("launchctl", "bootstrap", "gui/${uid()}", plistFile.absolutePath))
        if (bootstrap.exitCode != 0) {
            DesktopLog.e(TAG, "launchctl bootstrap failed (${bootstrap.exitCode}): ${bootstrap.output}")
            return false
        }
        val verify = exec(listOf("launchctl", "print", "gui/${uid()}/$LABEL"))
        if (verify.exitCode != 0) {
            DesktopLog.e(TAG, "agent not registered after bootstrap: ${verify.output}")
            return false
        }
        DesktopLog.i(TAG, "LaunchAgent installed -> ${resolveProgramArguments()}")
        return true
    }

    private fun removeAgent(): Boolean {
        val bootout = exec(listOf("launchctl", "bootout", "gui/${uid()}/$LABEL"))
        if (bootout.exitCode != 0) {
            DesktopLog.w(TAG, "launchctl bootout returned ${bootout.exitCode}: ${bootout.output}")
        }
        val deleted = !plistFile.exists() || plistFile.delete()
        if (!deleted) {
            DesktopLog.e(TAG, "could not delete ${plistFile.absolutePath}")
            return false
        }
        DesktopLog.i(TAG, "LaunchAgent removed")
        return true
    }

    // ---------------------------------------------------------------- process helpers

    data class ExecResult(val exitCode: Int, val output: String)

    private fun exec(command: List<String>, timeoutSeconds: Long = 20): ExecResult = runCatching {
        val process = ProcessBuilder(command).redirectErrorStream(true).start()
        val output = process.inputStream.bufferedReader().use { it.readText() }
        if (!process.waitFor(timeoutSeconds, TimeUnit.SECONDS)) {
            process.destroyForcibly()
            return ExecResult(-1, "timed out: ${command.joinToString(" ")}")
        }
        ExecResult(process.exitValue(), output.trim())
    }.getOrElse { ExecResult(-1, it.message ?: it.toString()) }

    private fun uid(): String = cachedUid ?: run {
        val value = exec(listOf("id", "-u")).output.trim().ifEmpty { "501" }
        cachedUid = value
        value
    }

    private companion object {
        const val TAG = "capabilities"
        const val LABEL = "dev.aliziwa.todo"
        const val INSTALLED_LAUNCHER = "/Applications/PersonalTodo.app/Contents/MacOS/PersonalTodo"
        /** Tells main() to start in the menu bar without opening a window at login. */
        const val BACKGROUND_FLAG = "--background"
        var cachedUid: String? = null

        fun String.escapeXml(): String =
            replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    }
}
